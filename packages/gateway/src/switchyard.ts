import { execFile } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { promisify } from "node:util";
import { mayaHome } from "@maya-ai/core";
import { InstanceSupervisor, scanModels } from "@maya-ai/model-runtime";

const execFileP = promisify(execFile);

/**
 * Switchyard (NVIDIA NeMo) is Maya's Anthropic⇄OpenAI translation sidecar
 * (owner directive 2026-07-08): coding agents speak their native Anthropic
 * Messages API to Maya, Switchyard translates, Maya's /v1 serves the request.
 * It's Python — isolated in its own venv under ~/.maya/runtimes/switchyard
 * (same pattern as the future MLX backend), supervised exactly like a model
 * instance: health checks, hung-kill, bounded restarts, orphan guard.
 */

export const SWITCHYARD_PORT = Number(process.env.MAYA_SWITCHYARD_PORT || 4310);

const venvDir = (): string => path.join(mayaHome(), "runtimes", "switchyard");
const binPath = (): string => path.join(venvDir(), "bin", "switchyard");
const configPath = (): string => path.join(mayaHome(), "switchyard", "config.yaml");

export interface SwitchyardInfo {
  installed: boolean;
  binPath?: string;
  version?: string;
  installHint?: string;
}

export async function detectSwitchyard(): Promise<SwitchyardInfo> {
  const bin = binPath();
  if (!fs.existsSync(bin)) {
    return {
      installed: false,
      installHint: "maya doctor --install-switchyard   (isolated venv; ~1 min; enables Anthropic-API agents like Claude Code)",
    };
  }
  try {
    const { stdout } = await execFileP(bin, ["--version"], { timeout: 30_000 });
    const version = stdout.trim().split(/\s+/).pop();
    return { installed: true, binPath: bin, ...(version ? { version } : {}) };
  } catch {
    return { installed: false, installHint: "venv exists but broken — remove ~/.maya/runtimes/switchyard and re-run maya doctor --install-switchyard" };
  }
}

/** Provision the isolated venv (requires uv). Explicit user action — never automatic. */
export async function provisionSwitchyard(onLine?: (s: string) => void): Promise<SwitchyardInfo> {
  const uv = await execFileP("uv", ["--version"], { timeout: 10_000 }).then(
    () => true,
    () => false,
  );
  if (!uv) throw new Error("uv is required to provision Switchyard: brew install uv");
  onLine?.("creating venv…");
  await execFileP("uv", ["venv", venvDir()], { timeout: 60_000 });
  onLine?.("installing nemo-switchyard (PyPI)…");
  await execFileP("uv", ["pip", "install", "--python", path.join(venvDir(), "bin", "python"), "nemo-switchyard[server]"], {
    timeout: 600_000,
  });
  return detectSwitchyard();
}

/** Turn a ModelId into a config-safe target key (target ids share the model namespace). */
const targetKey = (name: string): string => `t-${name.replace(/[^a-zA-Z0-9_-]/g, "-")}`;

/**
 * Generate the sidecar config from the current local catalog: one passthrough
 * target per local model, all pointing at Maya's own /v1. Each target's model
 * string (the ModelId) is exposed by Switchyard as an addressable model, so
 * agents can request exactly "local/<name>". Returns null when there are no
 * local models yet (config with zero targets is rejected by switchyard).
 */
export function generateSwitchyardConfig(modelsDir: string, gatewayPort: number): string | null {
  const models = scanModels(modelsDir);
  if (!models.length) return null;
  const lines: string[] = [
    "# Generated by Maya — do not edit (regenerated on model changes)",
    "endpoints:",
    "  maya:",
    "    api_key: none",
    `    base_url: http://127.0.0.1:${gatewayPort}/v1`,
    "",
    "targets:",
  ];
  for (const m of models) {
    lines.push(`  ${targetKey(m.name)}:`, "    endpoint: maya", `    model: local/${m.name}`, "    format: openai");
  }
  lines.push("", "profiles:", "  maya-default:", "    type: passthrough", `    target: ${targetKey(models[0]!.name)}`);
  return lines.join("\n") + "\n";
}

export interface SidecarHandle {
  supervisor: InstanceSupervisor;
  /** Current live port — flips atomically on blue/green refresh; gateway reads per-request. */
  port: number;
  /** Regenerate config from the catalog and swap in a fresh sidecar with zero dead window. */
  refresh(): Promise<void>;
  stop(): Promise<void>;
}

/** Write config + start the supervised sidecar. Returns null if not provisioned or no models. */
export async function startSwitchyard(modelsDir: string, gatewayPort: number): Promise<SidecarHandle | null> {
  const info = await detectSwitchyard();
  if (!info.installed || !info.binPath) return null;
  const config = generateSwitchyardConfig(modelsDir, gatewayPort);
  if (!config) return null;
  fs.mkdirSync(path.dirname(configPath()), { recursive: true });

  // Blue/green: refreshes boot the NEW sidecar on the alternate port with its
  // own config file, health-check it, atomically flip `handle.port` (the
  // gateway reads it per-request), then retire the old process. In-flight
  // requests finish on the old sidecar; new ones hit the new — no dead window.
  const configFor = (port: number): string => path.join(path.dirname(configPath()), `config-${port}.yaml`);
  const make = (port: number, cfg: string): InstanceSupervisor => {
    fs.writeFileSync(configFor(port), cfg);
    return new InstanceSupervisor({
      id: `switchyard-${port}`,
      binPath: info.binPath!,
      args: ["serve", "--config", configFor(port), "--host", "127.0.0.1", "--port", String(port)],
      port,
      healthUrl: `http://127.0.0.1:${port}/v1/models`,
      healthCheckIntervalMs: 10_000,
      hungProcessTimeoutMs: 60_000,
      maxRestarts: 3,
      restartWindowMs: 600_000,
      startupTimeoutMs: 60_000,
    });
  };

  let refreshing = false;
  const handle: SidecarHandle = {
    supervisor: make(SWITCHYARD_PORT, config),
    port: SWITCHYARD_PORT,
    async refresh() {
      if (refreshing) return; // coalesce concurrent refreshes (e.g. burst of pulls)
      refreshing = true;
      try {
        const next = generateSwitchyardConfig(modelsDir, gatewayPort);
        if (!next) return;
        const nextPort = handle.port === SWITCHYARD_PORT ? SWITCHYARD_PORT + 1 : SWITCHYARD_PORT;
        const green = make(nextPort, next);
        await green.start(); // health-checked ready before any traffic moves
        const blue = handle.supervisor;
        handle.supervisor = green;
        handle.port = nextPort; // atomic flip — gateway routes new requests here
        await blue.stop(); // graceful: in-flight requests drain on SIGTERM grace
      } finally {
        refreshing = false;
      }
    },
    async stop() {
      await handle.supervisor.stop();
    },
  };
  await handle.supervisor.start();
  return handle;
}
